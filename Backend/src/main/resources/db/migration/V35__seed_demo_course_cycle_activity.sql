-- 3. One booking per session of the class -----------------------------------------
DROP TEMPORARY TABLE IF EXISTS tmp_v35_book;
CREATE TEMPORARY TABLE tmp_v35_book (
  id INT AUTO_INCREMENT PRIMARY KEY, seq INT, user_id INT, schedule_id INT,
  start_time DATETIME, end_time DATETIME, booked_at DATETIME, keep_row TINYINT DEFAULT 1
);
INSERT INTO tmp_v35_book (seq, user_id, schedule_id, start_time, end_time, booked_at)
SELECT e.seq, e.user_id, s.schedule_id, s.start_time, s.end_time, e.enrolled_at
FROM tmp_v35_enroll e
JOIN SCHEDULES s ON s.class_id = e.class_id
WHERE s.status IN ('SCHEDULED', 'SUBSTITUTE_ASSIGNED', 'COMPLETED')
ORDER BY e.seq, s.start_time;

-- never double-book a member (existing bookings on the server win)
UPDATE tmp_v35_book t SET keep_row = 0
WHERE EXISTS (SELECT 1 FROM BOOKINGS b JOIN SCHEDULES s ON s.schedule_id = b.schedule_id
              WHERE b.user_id = t.user_id AND b.status = 'CONFIRMED'
                AND s.start_time < t.end_time AND s.end_time > t.start_time);

-- never overfill a session: keep the first enrolments until max_slots is reached
DROP TEMPORARY TABLE IF EXISTS tmp_v35_rank;
CREATE TEMPORARY TABLE tmp_v35_rank AS
SELECT t.id,
       ROW_NUMBER() OVER (PARTITION BY t.schedule_id ORDER BY t.seq) AS rn,
       (SELECT COUNT(*) FROM BOOKINGS b WHERE b.schedule_id = t.schedule_id AND b.status = 'CONFIRMED') AS taken,
       c.max_slots
FROM tmp_v35_book t
JOIN SCHEDULES s ON s.schedule_id = t.schedule_id
JOIN CLASSES c ON c.class_id = s.class_id
WHERE t.keep_row = 1;
UPDATE tmp_v35_book t JOIN tmp_v35_rank r ON r.id = t.id SET t.keep_row = 0 WHERE r.taken + r.rn > COALESCE(r.max_slots, 0);
DELETE FROM tmp_v35_book WHERE keep_row = 0;
DELETE e FROM tmp_v35_enroll e WHERE NOT EXISTS (SELECT 1 FROM tmp_v35_book t WHERE t.seq = e.seq);

